
/*
TASK 4: THEORY

1. Class aur Object mein kya farq hai?

Class ek design hoti hai jisme hum properties
aur methods banate hain. Object us class se banta hai.

Example:
Mobile ek class hai aur mobile1, mobile2 uske objects hain.


2. Getter aur Setter kyun banate hain?

Getter kisi value ko read karne ke liye hota hai.
Setter kisi value ko change karne ke liye hota hai.
Setter mein hum value check bhi kar sakte hain.

Example:
Wallet mein getter se balance dekh sakte hain
aur setter se PIN change kar sakte hain.


3. Static aur Normal property mein kya farq hai?

Static property sab objects ke liye same hoti hai.
Normal property har object ki apni hoti hai.

Example:
Wallet mein totalWallets static hai kyun ke
ye sab wallets ko count karta hai.
Har wallet ka balance alag hota hai.


4. final aur Private (_) mein kya farq hai?

final variable ki value ek baar set hone ke baad
dobara change nahi kar sakte.

Private property ke start mein underscore hota hai.
Isay doosri library se directly access nahi kar sakte.

Example:
Wallet mein owner final hai aur _balance private hai.


5. Positional aur Named parameters mein kya farq hai?

Positional parameters mein values order ke hisaab
se dete hain.

Example:
MobilePhone("Samsung", "A15", 45000, 30);

Named parameters mein parameter ka naam likhte hain,
jis se code samajhna easy hota hai.

Example:
Wallet(
  owner: "Ali",
  mobileNo: "0300-1234567",
  pin: "1234",
);

Flutter mein named parameters zyada use hote hain
kyun ke code readable hota hai.
*/
